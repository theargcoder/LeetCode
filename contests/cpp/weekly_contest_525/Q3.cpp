#include <unordered_map>
#include <vector>

class Solution
{
public:
  int countStaircase(const std::vector<int> &nums)
  {
    const auto size = nums.size();

    std::unordered_map<int, int> freq;
    std::multimap<int, int> freq_ordered;
    std::vector<int> ocurrance_order;

    int count = 0;

    for(size_t i = 0; i < size; i++)
    {
      ocurrance_order.clear();
      freq.clear();
      for(size_t j = i; j < size; j++)
      {
        freq_ordered.clear();
        if(ocurrance_order.empty() || ocurrance_order.back() != nums[j])
          ocurrance_order.push_back(nums[j]);
        freq[nums[j]]++;
        for(const auto &pair : freq)
        {
          freq_ordered.insert(std::make_pair(pair.second, pair.first));
        }

        bool found = true;
        int stair = 1;
        for(const auto &freq_pair : freq_ordered)
        {
          if(freq_pair.first != stair || freq_pair.second != ocurrance_order[stair - 1])
          {
            found = false;
            break;
          }
          stair++;
        }

        if(found)
          count++;
      }
    }

    return count;
  }
};

